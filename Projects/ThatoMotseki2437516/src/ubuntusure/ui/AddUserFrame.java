    private void saveUserButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveUserButtonActionPerformed
        // TODO add your handling code here:
        String firstname = firstnameField.getText().trim();
        String surname = surnameField.getText().trim();
        String username = usernameField.getText().trim();
        String email = emailField.getText().trim();

        String password = new String(JPasswordField.getPassword());
        String confirmPassword = new String(JConfirmPasswordField.getPassword());

// Validate required fields
        if (firstname.isEmpty() || surname.isEmpty()
                || username.isEmpty() || email.isEmpty()
                || password.isEmpty() || confirmPassword.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please complete all fields.");
            return;
        }

// Validate email format
        if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please enter a valid email address.");
            return;
        }

// Validate password length
        if (password.length() < 8) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Password must contain at least 8 characters.");
            return;
        }

// Confirm passwords
        if (!password.equals(confirmPassword)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Passwords do not match.");
            return;
        }

// Ensure a role is selected
        int selectedIndex = roleComboBox.getSelectedIndex();

        if (selectedIndex == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please select a user role.");
            return;
        }

        int roleID = (int) availableRoles.get(selectedIndex)[0];

        try {
            boolean success = userDAO.addUser(
                    firstname,
                    surname,
                    username,
                    password,
                    email,
                    roleID
            );

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "User account created successfully.");

                this.dispose();
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Could not create user account. Check whether the username "
                    + "or email already exists.\n" + e.getMessage()
            );
        }
    }//GEN-LAST:event_saveUserButtonActionPerformed

