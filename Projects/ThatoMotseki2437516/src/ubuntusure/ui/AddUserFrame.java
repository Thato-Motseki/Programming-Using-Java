    private void loadRoles() {
        try {
            availableRoles = userDAO.getAllRoles();

            roleComboBox.removeAllItems();

            for (Object[] role : availableRoles) {
                roleComboBox.addItem(role[1].toString());
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Could not load user roles: " + e.getMessage()
            );
        }
    }

