    private void viewDetailsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewDetailsButtonActionPerformed
        // TODO add your handling code here:

        int selectedRow = claimsTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a claim first.",
                    "No Claim Selected",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int modelRow = claimsTable.convertRowIndexToModel(selectedRow);

        int claimID = (int) claimsTable.getModel()
                .getValueAt(modelRow, 0);

        String claimNumber = claimsTable.getModel()
                .getValueAt(modelRow, 1).toString();

        String customerName = claimsTable.getModel()
                .getValueAt(modelRow, 2).toString();

        String policyNumber = claimsTable.getModel()
                .getValueAt(modelRow, 3).toString();

        String claimDate = claimsTable.getModel()
                .getValueAt(modelRow, 4).toString();

        java.math.BigDecimal claimAmount
                = new java.math.BigDecimal(
                        claimsTable.getModel()
                                .getValueAt(modelRow, 5).toString()
                );

        String claimStatus = claimsTable.getModel()
                .getValueAt(modelRow, 6).toString();

        JOptionPane.showMessageDialog(
                this,
                "Claim selected: " + claimNumber
                + "\nCustomer: " + customerName
                + "\nPolicy: " + policyNumber,
                "Selected Claim",
                JOptionPane.INFORMATION_MESSAGE
        );
    }//GEN-LAST:event_viewDetailsButtonActionPerformed

