    private void loadDashboardStatistics() {
        DashboardDAO dashboardDAO = new DashboardDAO();

        try {
            customersCountLabel.setText(
                    String.valueOf(dashboardDAO.getTotalCustomers())
            );

            policiesCountLabel.setText(
                    String.valueOf(dashboardDAO.getTotalPolicies())
            );

            claimsCountLabel.setText(
                    String.valueOf(dashboardDAO.getTotalClaims())
            );

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load dashboard statistics. Please check the database.",
                    "Dashboard Error",
                    JOptionPane.ERROR_MESSAGE
            );

            ex.printStackTrace();
        }

    }


