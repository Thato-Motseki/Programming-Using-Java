    private void saveUserButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveUserButtonActionPerformed
        // TODO add your handling code here:
        String firstname = firstnameField.getText().trim();
        String surname = surnameField.getText().trim();
        String username = usernameField.getText().trim();
        String email = emailField.getText().trim();

        String emailRegex = "^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$";

        if (firstname.isEmpty() || surname.isEmpty()
                || username.isEmpty() || email.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please complete all required fields.");
            return;
        }

        if (!email.matches(emailRegex)) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a valid email address.");
            return;
        }

        int selectedRole = roleComboBox.getSelectedIndex();

        if (selectedRole < 0 || selectedRole >= availableRoles.size()) {
            JOptionPane.showMessageDialog(this,
                    "Please select a valid user role.");
            return;
        }

        int roleID = (int) availableRoles.get(selectedRole)[0];

        try {
            boolean updated = userDAO.updateUser(
                    userID,
                    firstname,
                    surname,
                    username,
                    email,
                    roleID
            );

            if (updated) {
                JOptionPane.showMessageDialog(this,
                        "User details updated successfully.");

                dispose();
            } else {
                JOptionPane.showMessageDialog(this,
                        "No changes were saved.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Unable to update user. Check whether the username "
                    + "or email is already in use.\n" + e.getMessage(),
                    "Update Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_saveUserButtonActionPerformed

