    private void loadRoles() {

        try {
            availableRoles = userDAO.getAllRoles();

            roleComboBox.removeAllItems();

            for (Object[] role : availableRoles) {
                roleComboBox.addItem(role[1].toString());
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Could not load roles: " + e.getMessage());
        }
    }

    private void loadUserDetails() {

        try {
            Object[] user = userDAO.getUserByID(userID);

            if (user == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "User account could not be found.");
                dispose();
                return;
            }

            firstnameField.setText(user[0].toString());
            surnameField.setText(user[1].toString());
            usernameField.setText(user[2].toString());
            emailField.setText(user[3] == null ? "" : user[3].toString());

            int roleID = (int) user[4];

            for (int i = 0; i < availableRoles.size(); i++) {
                if ((int) availableRoles.get(i)[0] == roleID) {
                    roleComboBox.setSelectedIndex(i);
                    break;
                }
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Could not load user details: " + e.getMessage());
        }
    }

