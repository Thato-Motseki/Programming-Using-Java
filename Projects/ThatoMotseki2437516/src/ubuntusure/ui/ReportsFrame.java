    private void loadReport(String reportType) {
        currentReport = reportType;

        java.sql.Date fromDate = null;
        java.sql.Date toDate = null;

        try {
            if (!fromDateField.getText().trim().isEmpty()) {
                fromDate = java.sql.Date.valueOf(fromDateField.getText().trim());
            }

            if (!toDateField.getText().trim().isEmpty()) {
                toDate = java.sql.Date.valueOf(toDateField.getText().trim());
            }

            if (fromDate != null && toDate != null && fromDate.after(toDate)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "The From Date cannot be after the To Date."
                );
                return;
            }

            ubuntusure.dao.ReportsDAO dao = new ubuntusure.dao.ReportsDAO();

            java.util.List<Object[]> data;
            String[] columns;

            switch (reportType) {
                case "CUSTOMER":
                    columns = new String[]{
                        "Customer ID", "First Name", "Surname", "Email", "Phone Number"
                    };
                    data = dao.getCustomerReport();
                    break;

                case "POLICY":
                    columns = new String[]{
                        "Policy Number", "Customer", "Policy Type",
                        "Start Date", "End Date", "Annual Premium", "Status"
                    };
                    data = dao.getPolicyReport(fromDate, toDate);
                    break;

                case "CLAIMS":
                    columns = new String[]{
                        "Claim Number", "Customer", "Policy Number",
                        "Date Submitted", "Claim Amount", "Status"
                    };
                    data = dao.getClaimsReport(fromDate, toDate);
                    break;

                case "PAYMENTS":
                    columns = new String[]{
                        "Payment Reference", "Claim Number", "Payment Date",
                        "Payment Amount", "Payment Status"
                    };
                    data = dao.getPaymentsReport(fromDate, toDate);
                    break;

                default:
                    return;
            }

            javax.swing.table.DefaultTableModel model
                    = new javax.swing.table.DefaultTableModel(columns, 0);

            for (Object[] row : data) {
                model.addRow(row);
            }

            reportTable.setModel(model);

            if (data.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "No records found for this report."
                );
            }

        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter dates in YYYY-MM-DD format."
            );
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Could not generate report: " + e.getMessage()
            );
        }
    }

