    private void exportReportToCSV() {
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Save Report as CSV");
        chooser.setSelectedFile(new File(currentReport.toLowerCase() + "_report.csv"));

        int choice = chooser.showSaveDialog(this);

        if (choice == JFileChooser.APPROVE_OPTION) {
            File file = chooser.getSelectedFile();

            if (!file.getName().toLowerCase().endsWith(".csv")) {
                file = new File(file.getAbsolutePath() + ".csv");
            }

            try (FileWriter writer = new FileWriter(file)) {
                TableModel model = reportTable.getModel();

                // Write column headings
                for (int col = 0; col < model.getColumnCount(); col++) {
                    writer.write(escapeCSV(model.getColumnName(col)));

                    if (col < model.getColumnCount() - 1) {
                        writer.write(",");
                    }
                }
                writer.write("\n");

                // Write table data
                for (int row = 0; row < model.getRowCount(); row++) {
                    for (int col = 0; col < model.getColumnCount(); col++) {
                        Object value = model.getValueAt(row, col);
                        writer.write(escapeCSV(value == null ? "" : value.toString()));

                        if (col < model.getColumnCount() - 1) {
                            writer.write(",");
                        }
                    }
                    writer.write("\n");
                }

                JOptionPane.showMessageDialog(
                        this, "Report exported successfully."
                );

            } catch (IOException e) {
                JOptionPane.showMessageDialog(
                        this, "Could not export report: " + e.getMessage()
                );
            }
        }
    }

    private String escapeCSV(String value) {
        return "\"" + value.replace("\"", "\"\"") + "\"";
    }

