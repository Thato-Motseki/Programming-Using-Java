    private void configureCustomerTable() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{
                    "Customer ID",
                    "First Name",
                    "Surname",
                    "National ID",
                    "Phone Number",
                    "Email",
                    "Date of Birth"
                }, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        customersTable.setModel(model);
        // Display grid lines between rows and columns
        customersTable.setShowGrid(true);
        customersTable.setShowHorizontalLines(true);
        customersTable.setShowVerticalLines(true);

// Use subtle grey borders for a clean appearance
        customersTable.setGridColor(new java.awt.Color(220, 228, 235));

// Set spacing and row height
        customersTable.setIntercellSpacing(new java.awt.Dimension(1, 1));
        customersTable.setRowHeight(28);

// Set table colours
        customersTable.setBackground(java.awt.Color.WHITE);
        customersTable.setForeground(new java.awt.Color(35, 49, 66));

// Highlight selected rows in teal
        customersTable.setSelectionBackground(new java.awt.Color(20, 160, 145));
        customersTable.setSelectionForeground(java.awt.Color.WHITE);

// Keep customer records read-only and allow sorting
        customersTable.setAutoCreateRowSorter(true);

        customersTable.setRowHeight(25);
        customersTable.setAutoCreateRowSorter(true);

        customersTable.getTableHeader().setBackground(
                new java.awt.Color(18, 38, 63));

        customersTable.getTableHeader().setForeground(
                java.awt.Color.WHITE);

        customersTable.getTableHeader().setFont(
                new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 12));

        customersTable.getTableHeader().setReorderingAllowed(false);

        javax.swing.table.JTableHeader header
                = customersTable.getTableHeader();

        header.setBackground(new java.awt.Color(18, 38, 63));
        header.setForeground(java.awt.Color.WHITE);
        header.setFont(new java.awt.Font(
                "Segoe UI", java.awt.Font.BOLD, 12));

        header.setReorderingAllowed(false);
        header.setPreferredSize(new java.awt.Dimension(0, 34));
    }

    private void loadCustomers() {
        DefaultTableModel model
                = (DefaultTableModel) customersTable.getModel();

        model.setRowCount(0);

        try {
            CustomerDAO customerDAO = new CustomerDAO();
            List<Customer> customers = customerDAO.getAllCustomers();

            for (Customer customer : customers) {
                model.addRow(new Object[]{
                    customer.getCustomerID(),
                    customer.getFirstname(),
                    customer.getSurname(),
                    customer.getNationalID(),
                    customer.getPhoneNumber(),
                    customer.getEmail(),
                    customer.getDateOfBirth()
                });
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not load customer records.\n" + ex.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
            ex.printStackTrace();
        }

    }


