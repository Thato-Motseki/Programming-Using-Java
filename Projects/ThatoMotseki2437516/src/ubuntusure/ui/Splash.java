    private void startSplashTimer() {
        final int duration = 3000;
        final int interval = 30;
        final int totalSteps = duration / interval;

        loadingProgressBar.setMinimum(0);
        loadingProgressBar.setMaximum(100);
        loadingProgressBar.setValue(0);
        loadingProgressBar.setStringPainted(true);
        loadingProgressBar.setString("0%");

        final int[] step = {0};

        javax.swing.Timer timer = new javax.swing.Timer(interval, event -> {
            step[0]++;

            int progress = Math.min(
                    100,
                    (step[0] * 100) / totalSteps
            );

            loadingProgressBar.setValue(progress);
            loadingProgressBar.setString(progress + "%");

            if (progress >= 100) {
                ((javax.swing.Timer) event.getSource()).stop();
                loadingProgressBar.setForeground(new Color(0,0,122));

                javax.swing.Timer transitionTimer
                        = new javax.swing.Timer(100, transitionEvent -> {
                            LoginFrame loginFrame = new LoginFrame();
                            loginFrame.setLocationRelativeTo(null);
                            loginFrame.setVisible(true);
                            dispose();
                        });

                transitionTimer.setRepeats(false);
                transitionTimer.start();
            }
        });

        timer.start();
    }

