    private void toggleStatusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_toggleStatusButtonActionPerformed
        // TODO add your handling code here:
        int selectedRow = usersTable.getSelectedRow();

        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please select a user first.");
            return;
        }

        int userID = (int) usersTable.getValueAt(selectedRow, 0);

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to change this user's account status?",
                "Confirm Account Status",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            try {
                UserManagementDAO dao = new UserManagementDAO();

                if (dao.toggleUserStatus(userID)) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this, "User account status updated successfully.");
                    loadUsers();
                }

            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Could not update account status: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_toggleStatusButtonActionPerformed

