    private void loadUsers() {

        DefaultTableModel model
                = (DefaultTableModel) usersTable.getModel();

        model.setRowCount(0);

        try {
            UserManagementDAO dao = new UserManagementDAO();

            List<Object[]> users = dao.getAllUsers();

            int total = 0;
            int active = 0;
            int inactive = 0;

            for (Object[] user : users) {

                model.addRow(user);

                total++;

                if ("Active".equals(user[5])) {
                    active++;
                } else {
                    inactive++;
                }
            }

            totalUsersLabel.setText(String.valueOf(total));
            activeUsersLabel.setText(String.valueOf(active));
            inactiveUsersLabel.setText(String.valueOf(inactive));

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load users: " + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void searchUsers() {
        try {
            UserManagementDAO dao = new UserManagementDAO();

            String keyword = searchField.getText().trim();

            java.util.List<Object[]> users;

            if (keyword.isEmpty()) {
                users = dao.getAllUsers();
            } else {
                users = dao.searchUsers(keyword);
            }

            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) usersTable.getModel();

            model.setRowCount(0);

            for (Object[] user : users) {
                model.addRow(user);
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Search failed: " + e.getMessage());
        }
    }

