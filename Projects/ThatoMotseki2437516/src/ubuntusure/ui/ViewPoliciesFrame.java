    private void loadPolicies() {
        DefaultTableModel model
                = (DefaultTableModel) policiesTable.getModel();

        model.setRowCount(0);

        try {
            PolicyDAO policyDAO = new PolicyDAO();
            List<Object[]> policies = policyDAO.getAllPolicies();

            for (Object[] policy : policies) {
                model.addRow(policy);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Failed to load insurance policies.\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

