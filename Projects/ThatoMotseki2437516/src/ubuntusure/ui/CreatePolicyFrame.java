    private void policyTypeComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_policyTypeComboBoxActionPerformed
        // TODO add your handling code here:

        Object selectedItem = policyTypeComboBox.getSelectedItem();

        if (selectedItem == null) {
            return;
        }

        String policyType = selectedItem.toString();

        switch (policyType) {
            case "Motor":
                coverageLabel.setText("Vehicle Value (M):");
                break;

            case "Property":
                coverageLabel.setText("Property Value (M):");
                break;

            case "Life":
                coverageLabel.setText("Life Coverage Amount (M):");
                break;

            case "Health":
                coverageLabel.setText("Annual Coverage Limit (M):");
                break;

            default:
                coverageLabel.setText("Coverage / Insured Value:");
                break;
        }

        premiumField.setText("0.00");
        savePolicyButton.setEnabled(false);

        // Display the corresponding insurance tab
        String selectedType = policyTypeComboBox.getSelectedItem().toString();

        switch (selectedType) {
            case "Motor":
                policyTypeTabbedPane.setSelectedIndex(0);
                break;

            case "Property":
                policyTypeTabbedPane.setSelectedIndex(1);
                break;

            case "Life":
                policyTypeTabbedPane.setSelectedIndex(2);
                break;

            case "Health":
                policyTypeTabbedPane.setSelectedIndex(3);
                break;
        }

    }//GEN-LAST:event_policyTypeComboBoxActionPerformed

    private void calculateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateButtonActionPerformed
        // TODO add your handling code here:
        if (policyTypeComboBox.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this,
                    "Please select a policy type.");
            return;
        }

        String coverageText = coverageField.getText().trim();

        if (coverageText.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter the coverage amount.");
            return;
        }

        double coverage;

        try {
            coverage = Double.parseDouble(coverageText);

            if (coverage <= 0) {
                JOptionPane.showMessageDialog(this,
                        "Coverage amount must be greater than zero.");
                return;
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a valid numeric coverage amount.");
            return;
        }

        String policyType = policyTypeComboBox.getSelectedItem().toString();

        double rate = 0;

        switch (policyType) {
            case "Motor":
                rate = 0.05;
                break;

            case "Property":
                rate = 0.02;
                break;

            case "Life":
                rate = 0.03;
                break;

            case "Health":
                rate = 0.04;
                break;
        }

        double premium = coverage * rate;

        premiumField.setText(String.format("%.2f", premium));

    }//GEN-LAST:event_calculateButtonActionPerformed

    private void premiumFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_premiumFieldActionPerformed
        // TODO add your handling code here:

        // Confirm that a customer has been selected.
        if (customerComboBox.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a customer first.",
                    "Missing Customer",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Confirm that Motor Insurance has been selected.
        String policyType = String.valueOf(
                policyTypeComboBox.getSelectedItem()
        );

        if (!policyType.equals("Motor")) {
            JOptionPane.showMessageDialog(
                    this,
                    "For now, premium calculation is available for Motor Insurance only.",
                    "Policy Type",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        // Read and validate the vehicle value.
        double vehicleValue;

        try {
            vehicleValue = Double.parseDouble(
                    coverageField.getText().trim()
            );

            if (vehicleValue <= 0) {
                throw new NumberFormatException();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Enter a valid vehicle value greater than zero.",
                    "Invalid Vehicle Value",
                    JOptionPane.ERROR_MESSAGE
            );
            coverageField.requestFocus();
            return;
        }

        // Ask for the vehicle type.
        String[] vehicleTypes = {
            "Motorcycle",
            "Private Car",
            "Minibus",
            "Truck"
        };

        String vehicleType = (String) JOptionPane.showInputDialog(
                this,
                "Select the vehicle type:",
                "Motor Insurance",
                JOptionPane.QUESTION_MESSAGE,
                null,
                vehicleTypes,
                vehicleTypes[0]
        );

        if (vehicleType == null) {
            return;
        }

        // Ask for the type of cover.
        String[] coverTypes = {
            "Third Party",
            "Comprehensive"
        };

        String coverType = (String) JOptionPane.showInputDialog(
                this,
                "Select the type of cover:",
                "Motor Insurance",
                JOptionPane.QUESTION_MESSAGE,
                null,
                coverTypes,
                coverTypes[0]
        );

        if (coverType == null) {
            return;
        }

        // Determine the premium rate.
        double rate = 0;

        if (coverType.equals("Third Party")) {

            switch (vehicleType) {
                case "Motorcycle":
                    rate = 0.02;
                    break;

                case "Private Car":
                    rate = 0.025;
                    break;

                case "Minibus":
                    rate = 0.03;
                    break;

                case "Truck":
                    rate = 0.035;
                    break;
            }

        } else {

            switch (vehicleType) {
                case "Motorcycle":
                    rate = 0.04;
                    break;

                case "Private Car":
                    rate = 0.05;
                    break;

                case "Minibus":
                    rate = 0.06;
                    break;

                case "Truck":
                    rate = 0.07;
                    break;
            }
        }

        // Calculate and display the premium.
        double premium = vehicleValue * rate;

        premiumField.setText(String.format(
                java.util.Locale.US,
                "%.2f",
                premium
        ));

        JOptionPane.showMessageDialog(
                this,
                "Premium calculated successfully.\n\n"
                + "Vehicle Type: " + vehicleType + "\n"
                + "Cover Type: " + coverType + "\n"
                + "Vehicle Value: M " + String.format("%.2f", vehicleValue) + "\n"
                + "Premium Rate: " + String.format("%.2f%%", rate * 100) + "\n"
                + "Annual Premium: M " + String.format("%.2f", premium),
                "Premium Calculation Result",
                JOptionPane.INFORMATION_MESSAGE
        );

    }//GEN-LAST:event_premiumFieldActionPerformed

