package typeidentification;

/**
 *
 * @author thato
 */
public class TypeIdentification {

    public static void main(String[] args) {
        // Declare, assign and identify types
        String value1 = "90210";
        double value2 = 42.0;
        boolean value3 = true;
        char value4 = '-'; 
        int value5 = 0;

        // Print values and their types
        System.out.println("Value\t\tData Type");
        System.out.println("--------------------------");
        System.out.println(value1 + "\t\tString");
        System.out.println(value2 + "\t\tdouble");
        System.out.println(value3 + "\t\tboolean");
        System.out.println(value4 + "15\t\tchar / String");
        System.out.println(value5 + "\t\tint");
    }
}
